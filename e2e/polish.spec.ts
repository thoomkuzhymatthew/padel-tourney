import { test, expect } from '@playwright/test'

test('390px empty, duplicate, long-name and recovery states stay usable', async ({ page }) => {
  const externalFonts: string[] = []
  page.on('request', request => { if (/fonts\.(googleapis|gstatic)\.com/.test(request.url())) externalFonts.push('external font') })
  await page.goto('/')
  await expect(page.getByRole('link',{name:'Create tournament'})).toBeVisible()
  await expect(page.getByRole('link',{name:'Resume'})).toHaveCount(0)
  await page.getByRole('link',{name:'Create tournament'}).click()
  const draft=page.getByRole('textbox',{name:'Add a player'})
  await draft.fill('Alex Smith');await draft.press('Enter')
  await draft.fill(' alex   smith ')
  await expect(page.locator('#draft-name-error')).toContainText('already added')
  await draft.fill('Blair');await draft.press('Enter')
  await page.getByLabel('Player 2 name',{exact:true}).fill('Alex  Smith')
  await expect(page.locator('#player-name-error')).toContainText('same name')
  await expect(page.locator('.player-list input[aria-invalid="true"]')).toHaveCount(2)
  await expect(page.getByRole('button',{name:'Start',exact:true})).toBeDisabled()
  await page.screenshot({path:'artifacts/duplicate-names-mobile.png',fullPage:false})
  await page.getByLabel('Player 2 name',{exact:true}).fill('A very long player name that should remain editable on court')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const small=await page.locator('button,a,input,select').evaluateAll(elements=>elements.filter(element=>{
    const r=element.getBoundingClientRect(),style=getComputedStyle(element)
    return r.width>0&&r.height>0&&style.display!=='none'&&style.visibility!=='hidden'&&(r.width<48||r.height<48)
  }).length)
  expect(small).toBe(0)
  await page.route('**/rest/v1/rpc/get_tournament_snapshot', route=>route.fulfill({status:502,contentType:'text/html',body:'<html>Gateway unavailable</html>'}))
  await page.goto(`/t/${'a'.repeat(48)}`)
  await expect(page.getByRole('alert')).toContainText('incomplete response')
  await expect(page.getByRole('button',{name:'Try again'})).toBeVisible()
  await page.screenshot({path:'artifacts/error-mobile.png',fullPage:false})
  await page.unroute('**/rest/v1/rpc/get_tournament_snapshot')
  await page.getByRole('button',{name:'Try again'}).click()
  await expect(page.getByRole('alert')).toContainText('Tournament not found')
  expect(externalFonts).toEqual([])
})
